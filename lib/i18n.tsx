export type Lang = "th" | "en";
export type TKey = keyof typeof dict.th;

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  /** เลือกข้อความตามภาษา: อังกฤษถ้ามี ไม่งั้นใช้ภาษาไทย */
  tr: (th: string | null | undefined, en?: string | null) => string;
  /** ชื่อโต๊ะ: "โต๊ะ 2" → "Table 2" อัตโนมัติถ้าไม่ได้ใส่ชื่ออังกฤษ */
  tn: (name: string, en?: string | null) => string;
};

const LangCtx = createContext<Ctx>(null!);
export const useLang = () => useContext(LangCtx);

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("th");

  useEffect(() => {
    const s = localStorage.getItem("clickgo-lang");
    if (s === "en" || s === "th") setLangState(s);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("clickgo-lang", l);
  };
  const t = (k: TKey) => dict[lang][k];
  const tr = (th: string | null | undefined, en?: string | null) => (lang === "en" && en ? en : th ?? "");
  const tn = (name: string, en?: string | null) =>
    lang === "en" ? en || name.replace(/^โต๊ะ\s*/, "Table ") : name;

  return <LangCtx.Provider value={{ lang, setLang, t, tr, tn }}>{children}</LangCtx.Provider>;
}
